// Vendors boxicons from node_modules into the project so we don't depend on unpkg at runtime.
//
// Two outputs:
//   wwwroot/fonts/boxicons.woff2      - the icon font itself
//   src/css/boxicons.gen.css          - the icon classes, @font-face rewritten to point at our font
//
// The generated CSS is imported by src/css/main.css, so it ends up bundled into
// wwwroot/css/dist/main.css - no extra request for icons.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkgDir = resolve(projectRoot, "node_modules/boxicons");
const fontOutDir = resolve(projectRoot, "wwwroot/fonts");
const cssOut = resolve(projectRoot, "src/css/boxicons.gen.css");

// woff2 only: supported by every browser we target, and a third of the size of the
// woff/ttf/eot/svg fallbacks boxicons ships by default.
const FONT_FILE = "boxicons.woff2";

// main.css builds to wwwroot/css/dist/, so fonts resolve two levels up (matches raleway.css).
const FONT_FACE = `@font-face{font-family:boxicons;font-weight:400;font-style:normal;font-display:swap;src:url('../../fonts/${FONT_FILE}') format('woff2')}`;

mkdirSync(fontOutDir, { recursive: true });
copyFileSync(resolve(pkgDir, "fonts", FONT_FILE), resolve(fontOutDir, FONT_FILE));

const source = readFileSync(resolve(pkgDir, "css/boxicons.min.css"), "utf8");

// Swap the upstream @font-face (which points at ../fonts/ and lists five formats)
// for ours. No nested braces inside a @font-face block, so this match is safe.
const fontFacePattern = /@font-face\{[^}]*\}/;
if (!fontFacePattern.test(source)) {
    throw new Error("boxicons.min.css: no @font-face block found - package layout changed?");
}

const css = source.replace(fontFacePattern, FONT_FACE);
writeFileSync(cssOut, `/* Generated by scripts/vendor-boxicons.mjs - do not edit. */\n${css}\n`);

const { version } = JSON.parse(readFileSync(resolve(pkgDir, "package.json"), "utf8"));
console.log(`vendored boxicons ${version}: ${FONT_FILE} + boxicons.gen.css`);
